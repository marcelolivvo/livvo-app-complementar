export function generateSampleDataset(): SampleDataset {
  const photosMap = new Map<string, string>();
  SAMPLE_ARTISTS_DATA.forEach((a) => {
    photosMap.set(a.code, a.photoUrl);
    photosMap.set(a.name.trim().toLowerCase(), a.photoUrl);
  });

  const artists: ArtistItem[] = SAMPLE_ARTISTS_DATA.map((a) => {
    const showsCount = SAMPLE_SHOWS_LIST.filter((s) => s.artistCode === a.code).length;
    return {
      artistCode: a.code,
      artistName: a.name,
      photoUrl: a.photoUrl,
      featuredPosterUrl: a.featuredPosterUrl,
      photoSource: 'sample',
      showsCount,
      updatedAt: Date.now(),
    };
  });

  const shows: ShowItem[] = SAMPLE_SHOWS_LIST.map((s) => ({
    ...s,
    id: s.showCode,
  }));

  return { artists, shows, photosMap };
}
